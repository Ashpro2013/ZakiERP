    public static string ConvertToArabicNumbers(string input)
    {
        if (string.IsNullOrEmpty(input)) return input;
        return input.Replace("0", "٠")
                    .Replace("1", "١")
                    .Replace("2", "٢")
                    .Replace("3", "٣")
                    .Replace("4", "٤")
                    .Replace("5", "٥")
                    .Replace("6", "٦")
                    .Replace("7", "٧")
                    .Replace("8", "٨")
                    .Replace("9", "٩");
    }
    public static string GetFriendlyForeignKeyError(string rawMessage)
    {
        if (string.IsNullOrEmpty(rawMessage))
            return Localizer("ForeignKeyConstraintError");

        // Try to extract table name using Regex
        // Pattern matches: table "dbo.TableName" or table "TableName"
        var match = System.Text.RegularExpressions.Regex.Match(rawMessage, "table \"(dbo\\.)?(\\w+)\"");

        if (match.Success)
        {
            string tableName = match.Groups[2].Value; // Group 2 captures the table name without dbo.
            string friendlyName = GetFriendlyTableName(tableName);

            return AppData.IsArabic
               ? $"لا يمكن حذف هذا البند لارتباطه بسجلات في: {friendlyName}"
               : $"Cannot delete this item because it is referenced in: {friendlyName}";
        }

        return Localizer("ForeignKeyConstraintError");
    }
